#!/usr/bin/env bash
# Regenerate stacks/skeleton-hashes.txt: the sha256 of EVERY version ever shipped of every framework skeleton
# (stacks/<stack>/frameworks/<fw>/skeletons/<file>), from git history + the working tree.
# kit upgrade uses it to tell whether a project's shared skeleton was a framework's file (any version) before 0.11.
# Run after changing a framework skeleton; tests/regressions.sh fails while a current hash is missing.
set -euo pipefail
cd "$(cd "$(dirname "$0")/.." && pwd)"
sha() { if command -v shasum >/dev/null 2>&1; then shasum -a 256 | cut -d' ' -f1; else sha256sum | cut -d' ' -f1; fi; }
{
  echo "# sha256  <stack>/<framework>/<file> — every shipped version of each framework skeleton (generated by scripts/skeleton-hashes.sh)"
  {
    for p in $( { git log --all --format= --name-only -- 'stacks/*/frameworks/*/skeletons/*'; ls stacks/*/frameworks/*/skeletons/* 2>/dev/null; } | sort -u); do
      key="$(printf '%s' "$p" | sed -E 's#^stacks/([^/]+)/frameworks/([^/]+)/skeletons/#\1/\2/#')"
      for c in $(git log --all --format=%H -- "$p"); do
        if git cat-file -e "$c:$p" 2>/dev/null; then printf '%s  %s\n' "$(git show "$c:$p" | sha)" "$key"; fi
      done
      if [ -f "$p" ]; then printf '%s  %s\n' "$(sha < "$p")" "$key"; fi   # deleted since: history only, no failing status
    done
  } | sort -k2 -k1 -u
} > stacks/skeleton-hashes.txt
echo "stacks/skeleton-hashes.txt: $(grep -vc '^#' stacks/skeleton-hashes.txt) hash(es)"
